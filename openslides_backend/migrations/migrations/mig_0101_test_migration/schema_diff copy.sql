CREATE TABLE assignment_category_t (
    id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name varchar(256)
    CONSTRAINT required_assignment_category_name NOT NULL,
    prefix varchar(256),
    weight integer
    CONSTRAINT default_assignment_category_weight DEFAULT 10000,
    level integer,
    sequential_number integer
    CONSTRAINT required_assignment_category_sequential_number NOT NULL,
    CONSTRAINT unique_assignment_category_sequential_number_meeting_id
        UNIQUE (sequential_number, meeting_id),
    parent_id integer,
    meeting_id integer
    CONSTRAINT required_assignment_category_meeting_id NOT NULL
);
ALTER TABLE assignment_t ADD COLUMN category_id integer;

CREATE VIEW "assignment_category" AS SELECT
    *,
    (
        SELECT
            array_agg(
                ac.id
                ORDER BY ac.id
            )
        FROM assignment_category_t AS ac
        WHERE ac.parent_id = a.id
    ) AS child_ids,
    (
        SELECT
            array_agg(
                ast.id
                ORDER BY ast.id
            )
        FROM assignment_t AS ast
        WHERE ast.category_id = a.id
    ) AS assignment_ids
FROM assignment_category_t AS a;

